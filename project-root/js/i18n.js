function readStoredLanguage() {
    try {
        const stored = localStorage.getItem(STORAGE_KEY);
        return LANGUAGES.includes(stored) ? stored : DEFAULT_LANGUAGE;
    } catch {
        return DEFAULT_LANGUAGE; // storage blocked (private mode etc.)
    }
}

let currentLanguage = readStoredLanguage();
document.documentElement.lang = currentLanguage;

export function getLanguage() {
    return currentLanguage;
}

export function setLanguage(language) {
    if (!LANGUAGES.includes(language)) {
        return;
    }
    currentLanguage = language;
    document.documentElement.lang = language;
    try {
        localStorage.setItem(STORAGE_KEY, language);
    } catch {
        // not saved, but still applies for this visit
    }
}

// Locale for dates and numbers (id-ID: 27 Nov 2026, Rp 48.500.000).
export function getLocale() {
    return currentLanguage === 'en' ? 'en-GB' : 'id-ID';
}

export function t(key, params = {}) {
    let template = messages[currentLanguage][key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
    if (template.includes('|')) {
        const [one, other] = template.split('|');
        template = Number(params.count) === 1 ? one : other;
    }
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// For checks: keys present in one language but not the other.
export function missingTranslations() {
    const id = Object.keys(messages.id);
    const en = Object.keys(messages.en);
    return {
        missingInEnglish: id.filter((key) => !(key in messages.en)),
        missingInIndonesian: en.filter((key) => !(key in messages.id))
    };
}
